-- 身份聚合：account（身份与归属）+ account_info（名字、状态与唯一认证哈希）。
-- DDL 与 docs/biz-data-model.md §4.1、§4.2 逐字一致；外键一律逻辑外键，不写 references。

create table account (
    id               bigint      generated by default as identity (start with 100000000) primary key,
    type             text        not null,
    owner_account_id bigint,
    turms_sync_state text        not null default 'pending',
    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now(),
    constraint account_type_chk   check (type in ('human', 'agent')),
    constraint account_sync_chk   check (turms_sync_state in ('pending', 'synced')),
    constraint account_owner_chk  check ((type = 'agent') = (owner_account_id is not null)),
    constraint account_no_self_owner_chk check (owner_account_id is null or owner_account_id <> id)
);

create index account_owner_idx on account (owner_account_id) where owner_account_id is not null;

create table account_info (
    account_id      bigint      primary key,
    display_name    text        not null,
    status          text        not null default 'active',
    email           text,
    credential_hash text        not null,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    constraint account_info_name_chk check (length(btrim(display_name)) > 0),
    constraint account_info_status_chk check (status in ('active', 'frozen')),
    constraint account_info_email_uq unique (email),
    constraint account_info_credential_uq unique (credential_hash),
    constraint account_info_email_normalized_chk check (
        email is null or email = lower(btrim(email))
    ),
    constraint account_info_email_shape_chk check (
        email is null or position('@' in email) > 1
    )
);
