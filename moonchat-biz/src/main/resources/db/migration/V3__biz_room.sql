-- 群聚合：room_info（群与群主）+ room_member（成员唯一真相）+ account_room（同事务镜像）。
-- DDL 与 docs/biz-data-model.md §4.5、§4.6、§4.7 逐字一致。S1 只用建表，读写随 S3。

create table room_info (
    id               bigint      generated by default as identity primary key,
    name             text        not null,
    owner_account_id bigint      not null,
    turms_group_id   bigint,
    turms_sync_state text        not null default 'pending',
    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now(),
    constraint room_info_name_chk      check (length(btrim(name)) > 0),
    constraint room_info_sync_chk      check (turms_sync_state in ('pending', 'synced')),
    constraint room_info_turms_group_uq unique (turms_group_id)
);

create table room_member (
    room_id    bigint      not null,
    account_id bigint      not null,
    joined_at  timestamptz not null default now(),
    deleted_at timestamptz,
    constraint room_member_pk primary key (room_id, account_id)
);

create index room_member_deleted_at_idx
    on room_member (deleted_at)
    where deleted_at is not null;

create table account_room (
    account_id bigint      not null,
    room_id    bigint      not null,
    joined_at  timestamptz not null default now(),
    deleted_at timestamptz,
    constraint account_room_pk primary key (account_id, room_id)
);

create index account_room_deleted_at_idx
    on account_room (deleted_at)
    where deleted_at is not null;
