-- 关系聚合：friendship（唯一真相，规范序小 id 在前）+ friendship_reverse（同事务维护的查询镜像）。
-- DDL 与 docs/biz-data-model.md §4.3、§4.4 逐字一致。S1 只用建表，读写随 S2。

create table friendship (
    id              bigint      generated by default as identity primary key,
    account_id      bigint      not null,
    peer_account_id bigint      not null,
    status          text        not null,
    requested_by    bigint      not null,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    deleted_at      timestamptz,
    constraint friendship_status_chk   check (status in ('pending', 'accepted')),
    constraint friendship_order_chk    check (account_id < peer_account_id),
    constraint friendship_requester_chk check (requested_by in (account_id, peer_account_id)),
    constraint friendship_pair_uq      unique (account_id, peer_account_id)
);

create index friendship_deleted_at_idx
    on friendship (deleted_at)
    where deleted_at is not null;

create table friendship_reverse (
    account_id      bigint      not null,
    peer_account_id bigint      not null,
    friendship_id   bigint      not null,
    status          text        not null,
    requested_by    bigint      not null,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    deleted_at      timestamptz,
    constraint friendship_reverse_pk           primary key (account_id, peer_account_id),
    constraint friendship_reverse_friendship_uq unique (friendship_id),
    constraint friendship_reverse_status_chk   check (status in ('pending', 'accepted')),
    constraint friendship_reverse_order_chk    check (account_id > peer_account_id),
    constraint friendship_reverse_requester_chk check (requested_by in (account_id, peer_account_id))
);

create index friendship_reverse_deleted_at_idx
    on friendship_reverse (deleted_at)
    where deleted_at is not null;
